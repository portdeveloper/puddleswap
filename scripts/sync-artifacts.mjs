#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const ADDRESS_FILE = path.join(ROOT, "config/addresses/10143.json");
const OUTPUT_FILE = path.join(ROOT, "web/src/config/generated.ts");

const artifacts = {
  usdc: [],
  testUSDT: ["contracts/out/TestUSDT.sol/TestUSDT.json"],
  stableFaucet: ["contracts/out/StableFaucet.sol/StableFaucet.json"],
  tokenRegistry: ["contracts/out/TokenRegistry.sol/TokenRegistry.json"],
  openRegistrationGate: ["contracts/out/OpenRegistrationGate.sol/OpenRegistrationGate.json"],
  registrationPass: ["contracts/out/RegistrationPass.sol/RegistrationPass.json"],
  passRegistrationGate: ["contracts/out/PassRegistrationGate.sol/PassRegistrationGate.json"],
  uniswapV2Factory: ["contracts/out/UniswapV2Factory.sol/UniswapV2Factory.json"],
  uniswapV2Router02: ["contracts/out/UniswapV2Router02.sol/UniswapV2Router02.json"],
  wmon: ["contracts/out/WMON.sol/WMON.json"]
};

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function readArtifactAbi(candidates) {
  for (const candidate of candidates) {
    const fullPath = path.join(ROOT, candidate);
    if (fs.existsSync(fullPath)) {
      const artifact = readJson(fullPath);
      return artifact.abi ?? [];
    }
  }
  return [];
}

const addresses = fs.existsSync(ADDRESS_FILE)
  ? readJson(ADDRESS_FILE)
  : {
      chainId: 10143,
      updatedAt: "",
      contracts: {}
    };

const abiByContract = {};
for (const [name, candidates] of Object.entries(artifacts)) {
  abiByContract[name] = readArtifactAbi(candidates);
}

const fileBody = `// Auto-generated by scripts/sync-artifacts.mjs\n\nexport const deployment = ${JSON.stringify(
  addresses,
  null,
  2
)} as const;\n\nexport const abis = ${JSON.stringify(abiByContract, null, 2)} as const;\n`;

fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
fs.writeFileSync(OUTPUT_FILE, fileBody);

console.log(`Wrote ${OUTPUT_FILE}`);
